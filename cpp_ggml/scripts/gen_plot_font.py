#!/usr/bin/env python3
"""Generate src/plot_font.inc — the glyph atlas the C++ distribution plots use.

Dev-time only (the C++ runtime embeds the generated data; no python/font file
is needed at run time). Rasterizes printable ASCII with DejaVu Sans — the
matplotlib default face the official gaussian_*_distribution.png use — into a
single-row 8-bit coverage atlas, PNG-encoded and base64-embedded.

    python cpp_ggml/scripts/gen_plot_font.py
"""
import base64
import io
import os

import matplotlib
from PIL import Image, ImageDraw, ImageFont

PX = 32  # rasterization size; the plotter scales down per requested size
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "plot_font.inc")


def main():
    ttf = os.path.join(matplotlib.get_data_path(), "fonts", "ttf", "DejaVuSans.ttf")
    font = ImageFont.truetype(ttf, PX)
    ascent, descent = font.getmetrics()
    cell_h = ascent + descent
    chars = [chr(c) for c in range(32, 127)]
    widths = [max(1, int(round(font.getlength(ch)))) for ch in chars]
    xs, x = [], 0
    for w in widths:
        xs.append(x)
        x += w + 2  # 2px gutter: no bleed when bilinear-sampling a neighbour
    atlas = Image.new("L", (x, cell_h), 0)
    draw = ImageDraw.Draw(atlas)
    for ch, gx in zip(chars, xs):
        draw.text((gx, 0), ch, font=font, fill=255)
    buf = io.BytesIO()
    atlas.save(buf, format="PNG", optimize=True)
    b64 = base64.b64encode(buf.getvalue()).decode("ascii")
    lines = [b64[i:i + 96] for i in range(0, len(b64), 96)]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// generated by scripts/gen_plot_font.py — DejaVu Sans "
                f"{PX}px coverage atlas (printable ASCII)\n")
        f.write(f"constexpr int kFontPx = {PX};\n")
        f.write(f"constexpr int kFontAscent = {ascent};\n")
        f.write(f"constexpr int kFontCellH = {cell_h};\n")
        f.write("constexpr int kGlyphX[95] = {" + ", ".join(map(str, xs)) + "};\n")
        f.write("constexpr int kGlyphW[95] = {" + ", ".join(map(str, widths)) + "};\n")
        f.write("constexpr const char* kFontAtlasB64 =\n")
        for ln in lines:
            f.write(f'    "{ln}"\n')
        f.write("    ;\n")
    print(f"wrote {OUT}: atlas {x}x{cell_h}, png {len(buf.getvalue())} B")


if __name__ == "__main__":
    main()
